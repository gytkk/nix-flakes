def test_runtime_skill_requires_valid_document(tmp_path: Path) -> None:
    missing_root = tmp_path / "missing"
    (missing_root / "missing-document").mkdir(parents=True)
    with pytest.raises(core.ValidationError, match="missing SKILL.md"):
        core.materialize("codex", [missing_root])

    invalid_root = tmp_path / "invalid"
    invalid_skill = invalid_root / "invalid-frontmatter"
    invalid_skill.mkdir(parents=True)
    (invalid_skill / "SKILL.md").write_text("# Missing frontmatter\n")
    with pytest.raises(
        core.ValidationError, match="missing or invalid SKILL.md frontmatter"
    ):
        core.materialize("codex", [invalid_root])

    mismatch_root = tmp_path / "mismatch"
    write_skill(mismatch_root, "directory-name", declared_name="declared-name")
    with pytest.raises(
        core.ValidationError, match="skill directory-name/name mismatch"
    ):
        core.materialize("codex", [mismatch_root])


def test_runtime_skill_roots_reject_symlinks(tmp_path: Path) -> None:
    real_root = tmp_path / "real"
    skill = write_skill(real_root, "linked-content")
    (skill / "target.md").write_text("target\n")
    (skill / "linked.md").symlink_to(skill / "target.md")

    with pytest.raises(core.ValidationError, match="unsafe skill source path"):
        core.materialize("codex", [real_root])

    linked_root = tmp_path / "linked-root"
    linked_root.symlink_to(real_root, target_is_directory=True)
    with pytest.raises(core.ValidationError, match="unsafe runtime skill root"):
        core.materialize("codex", [linked_root])


def test_cli_accepts_repeated_runtime_skill_roots(tmp_path: Path) -> None:
    first_root = tmp_path / "first"
    second_root = tmp_path / "second"
    write_skill(first_root, "runtime-one")
    write_skill(second_root, "runtime-two")
    output = tmp_path / "output"

    assert (
        main(
            [
                "render",
                "--runtime",
                "codex",
                "--runtime-skill-root",
                str(first_root),
                "--runtime-skill-root",
                str(second_root),
                "--output",
                str(output),
            ]
        )
        == 0
    )
    assert (output / "skills/runtime-one/SKILL.md").is_file()
    assert (output / "skills/runtime-two/SKILL.md").is_file()


def test_cli_help_describes_commands_and_render_arguments(
    capsys: pytest.CaptureFixture[str],
) -> None:
    with pytest.raises(SystemExit) as top_level_exit:
        main(["--help"])
    assert top_level_exit.value.code == 0
    top_level_help = capsys.readouterr().out
    assert "Render and validate shared instructions and skills" in top_level_help
    assert "render" in top_level_help
    assert "check" in top_level_help
    assert "verify-install" in top_level_help
    assert "examples:" in top_level_help

    with pytest.raises(SystemExit) as render_exit:
        main(["render", "--help"])
    assert render_exit.value.code == 0
    render_help = capsys.readouterr().out
    normalized_render_help = " ".join(render_help.split())
    assert "optional runtime-specific skills" in normalized_render_help
    assert "--runtime-skill-root" in render_help
    assert "Missing or empty directory" in normalized_render_help


def test_verify_install_reports_all_difference_kinds(tmp_path: Path) -> None:
    expected, actual = tmp_path / "expected", tmp_path / "actual"
    expected.mkdir()
    actual.mkdir()
    (expected / "missing").write_text("x")
    (actual / "unexpected").write_text("x")
    (expected / "type").write_text("x")
    (actual / "type").mkdir()
    (expected / "bytes").write_text("expected")
    (actual / "bytes").write_text("actual")
    (expected / "link").symlink_to("one")
    (actual / "link").symlink_to("two")
    differences = core.compare_trees(expected, actual)
    assert "missing: missing" in differences
    assert "unexpected: unexpected" in differences
    assert any(item.startswith("type differs: type") for item in differences)
    assert "bytes differ: bytes" in differences
    assert "symlink target differs: link" in differences


