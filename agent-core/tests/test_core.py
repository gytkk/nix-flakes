def test_runtime_skill_roots_are_merged_and_deterministic(tmp_path: Path) -> None:
    first_root = tmp_path / "first"
    second_root = tmp_path / "second"
    first_skill = write_skill(first_root, "runtime-one")
    write_skill(second_root, "runtime-two")
    (first_skill / "reference.md").write_bytes(b"runtime reference\n")

    first = core.materialize("codex", [first_root, second_root])
    second = core.materialize("codex", [first_root, second_root])

    assert first == second
    assert core.output_hash(first) == core.output_hash(second)
    assert (
        b"Generated by agent-core"
        in first[PurePosixPath("skills/runtime-one/SKILL.md")]
    )
    assert (
        first[PurePosixPath("skills/runtime-one/reference.md")]
        == b"runtime reference\n"
    )
    assert PurePosixPath("skills/runtime-two/SKILL.md") in first


def test_runtime_skill_cannot_replace_portable_skill(tmp_path: Path) -> None:
    runtime_root = tmp_path / "runtime"
    write_skill(runtime_root, "tdd")

    with pytest.raises(core.ValidationError, match="duplicate skill name: tdd"):
        core.materialize("codex", [runtime_root])


